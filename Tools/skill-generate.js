#!/usr/bin/env node
"use strict";

/**
 * skill-generate.js — draft a new skill from a procedural workflow.
 * Writes ONLY to Skills/_drafts/ (status: draft, quality: 0). Human approval
 * moves it into Skills/ + promote + regenerate index. Spec §7.
 */

const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");
const PROC = path.join(ROOT, "Memory", "procedural");
const SKILLS = path.join(ROOT, "Skills");
const DRAFTS = path.join(SKILLS, "_drafts");
const MANIFEST = path.join(ROOT, "Tools", "manifest.json");

function parseArgs(argv) {
  const a = { scan: false, from: "", role: "Builder", name: "", out: DRAFTS, skills: SKILLS, procedural: PROC, manifest: MANIFEST, dry: false };
  for (let i = 0; i < argv.length; i++) {
    const v = argv[i];
    if (v === "--scan") a.scan = true;
    else if (v === "--from") a.from = argv[++i] || "";
    else if (v === "--role") a.role = argv[++i] || "Builder";
    else if (v === "--name") a.name = argv[++i] || "";
    else if (v === "--out") a.out = path.resolve(argv[++i] || ".");
    else if (v === "--skills") a.skills = path.resolve(argv[++i] || ".");
    else if (v === "--procedural") a.procedural = path.resolve(argv[++i] || ".");
    else if (v === "--manifest") a.manifest = path.resolve(argv[++i] || ".");
    else if (v === "--dry") a.dry = true;
  }
  return a;
}

const STOP = new Set(["a","an","the","and","or","of","to","in","on","for","with","is","are","be","into","from","as","at","by","this","that","it","its","how","what","when","do","does","not","no","if","then","else","up","down","out","off","over","under","again","further","once","here","there","all","any","both","each","few","more","most","other","some","such","only","own","same","so","than","too","very","can","will","just","should","now"]);

function readTitle(text) {
  const m = text.match(/^#\s+(?:AI-Suplex Procedural Memory[^\w]*)?(.+)$/m);
  return m ? m[1].trim() : "Untitled Workflow";
}
function readPurpose(text) {
  const m = text.match(/## Purpose\s*\n([\s\S]*?)(?=\n## |$)/);
  return m ? m[1].split("\n").map(l => l.trim()).filter(Boolean).join(" ").trim() : "";
}
function countSteps(text) {
  const m = text.match(/## Procedure\s*\n([\s\S]*?)(?=\n## |$)/);
  return m ? (m[1].match(/^\d+\./gm) || []).length : 0;
}
function oneSentence(s) {
  if (!s) return "";
  return (s.split(/[.!?]\s+/)[0] + ".").replace(/"/g, "'").replace(/:/g, "-");
}
function triggers(title, purpose) {
  const seen = new Set();
  const out = [];
  for (const w of (title + " " + purpose).toLowerCase().split(/[^a-z0-9]+/)) {
    if (w.length > 2 && !STOP.has(w) && !seen.has(w)) { seen.add(w); out.push(w); }
  }
  return out.slice(0, 5);
}
function toolsUsed(body, manifestPath) {
  const used = [];
  if (fs.existsSync(manifestPath)) {
    try {
      const tools = JSON.parse(fs.readFileSync(manifestPath, "utf8")).tools || [];
      for (const t of tools) if (body.includes(t.id)) used.push(t.id);
    } catch (e) {}
  }
  return used;
}
function existingNames(skillsDir) {
  const names = new Set();
  if (!fs.existsSync(skillsDir)) return names;
  for (const f of fs.readdirSync(skillsDir)) {
    if (f.endsWith(".md") && f !== "index.md") {
      const m = fs.readFileSync(path.join(skillsDir, f), "utf8").match(/skill_name:\s*"([^"]+)"/);
      if (m) names.add(m[1]);
    }
  }
  return names;
}

function buildDraft(a, text) {
  const title = a.name || readTitle(text);
  const purpose = readPurpose(text);
  const desc = oneSentence(purpose);
  const name = a.role + " – " + title;
  const t = triggers(title, purpose);
  const u = toolsUsed(text, a.manifest);
  const steps = countSteps(text);
  const today = new Date().toISOString().slice(0, 10);
  const lines = [
    "---",
    "type: skill",
    'skill_name: "' + name + '"',
    'role: "' + a.role + '"',
    'version: "0.1"',
    "date: " + today,
    "tags: [skill, draft]",
    'description: "' + desc + '"',
    "triggers: [" + t.join(", ") + "]",
    "depends_on: []",
    "uses_tools: " + (u.length ? "[" + u.join(", ") + "]" : "[]"),
    "quality: 0",
    "status: draft",
    "source_procedure: " + path.basename(a.from),
    "---",
    "",
    "# " + a.role + " Skill: " + title,
    "",
    "> Draft generated by Tools/skill-generate.js — review before promoting to Skills/.",
    "",
    "## 🎯 Purpose",
    purpose,
    "",
    "## 📥 When to Use",
    "(to be filled during review)",
    "",
    "## 📤 What to Do",
    "(ported from the procedure; " + steps + " steps — see source_procedure)",
    "",
    "## ✅ Output",
    "(to be filled during review)",
    "",
    "## 🧠 Memory loop",
    'node Tools/3lm.js add-lessons --source skill --ref "' + title + '" --list "..." && node Tools/3lm.js index',
    "",
  ];
  return { name, filename: name + ".md", content: lines.join("\n"), steps, purpose };
}

function reviewChecklist(a, name, steps, purpose, existing) {
  const lines = ["Review checklist:"];
  lines.push("  [ ] Duplicate? — " + (existing.has(name) ? 'WARNING: a skill named "' + name + '" already exists' : "none found"));
  const stdRoles = ["Architect", "Builder", "Orchestrator", "Sweeper", "Hustler"];
  lines.push("  [ ] Role valid? — " + (stdRoles.indexOf(a.role) >= 0 ? a.role + " is a standard role" : "WARNING: " + a.role + " is not a standard role"));
  lines.push("  [ ] Purpose present? — " + (purpose ? "yes" : "WARNING: no Purpose section found"));
  lines.push("  [ ] Actionable? — " + steps + " numbered step(s)");
  lines.push("  [ ] Focus assigned? — assign a focus before approval");
  lines.push("Approval path: move the draft to Skills/ + set status: active, then:");
  lines.push("  node Tools/3lm.js promote --min 70");
  lines.push("  node Tools/refresh-skill-index.js");
  return lines.join("\n");
}

function cmdScan(a) {
  const files = fs.existsSync(a.procedural) ? fs.readdirSync(a.procedural).filter(f => f.endsWith(".md") && f.indexOf("promoted") !== 0) : [];
  const rows = [];
  for (const f of files) {
    const text = fs.readFileSync(path.join(a.procedural, f), "utf8");
    rows.push({ title: readTitle(text), steps: countSteps(text), purpose: readPurpose(text) });
  }
  rows.sort((x, y) => y.steps - x.steps || x.title.localeCompare(y.title));
  console.log("Candidates from " + a.procedural + " (the 'succeeded 3x' bar is yours to judge):");
  if (rows.length === 0) console.log("  (none)");
  rows.forEach((r, i) => console.log("  " + (i + 1) + ". " + r.title + " — " + r.steps + " steps — " + (r.purpose ? r.purpose.slice(0, 70) : "")));
}

function cmdFrom(a) {
  if (!fs.existsSync(a.from)) { console.error("skill-generate: file not found: " + a.from); process.exit(2); }
  const text = fs.readFileSync(a.from, "utf8");
  const d = buildDraft(a, text);
  const existing = existingNames(a.skills);
  const checklist = reviewChecklist(a, d.name, d.steps, d.purpose, existing);
  if (a.dry) {
    console.log(d.content);
    console.log("---");
    console.log(checklist);
    return;
  }
  fs.mkdirSync(a.out, { recursive: true });
  fs.writeFileSync(path.join(a.out, d.filename), d.content);
  console.log("Drafted → " + path.join(a.out, d.filename));
  console.log(checklist);
}

function main() {
  const a = parseArgs(process.argv.slice(2));
  if (a.scan) cmdScan(a);
  else if (a.from) cmdFrom(a);
  else { console.error("usage: node Tools/skill-generate.js (--scan | --from <file>) [--role r] [--dry]"); process.exit(2); }
}

main();
